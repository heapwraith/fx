#!/usr/bin/env python3
"""Writes THIRD-PARTY-NOTICES.txt (T5.2): every crate compiled into the
programs fx ships (fx, fx-indexd, fx-preview, fx-setup, fx-setup-boot; normal
dependencies for Windows x64, not build or test ones), with its license and
the license and NOTICE files it carries. A text that repeats word for word
(the Apache 2.0 license, for one) is written once and referred to after.

Run from the repository root: python3 tools/third-party-notices.py
The installer carries the file (fx-setup --pack, DOCUMENTS).
"""

import json
import pathlib
import re
import subprocess
import sys

ROOTS = ["fx-ui", "fx-indexd", "fx-preview", "fx-setup", "fx-setup-boot"]
TARGET = "x86_64-pc-windows-msvc"
FILES = re.compile(r"^(licen[cs]e|copying|notice|copyright|unlicense)", re.I)


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--filter-platform", TARGET],
        check=True,
        capture_output=True,
        # cargo writes UTF-8; without this, Python on Windows decodes it with
        # the ANSI code page and mangles authors' names (CI runs on Windows).
        encoding="utf-8",
    ).stdout
    return json.loads(out)


def shipped(meta):
    """Package ids reachable from the roots through normal dependencies."""
    by_id = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    roots = [p["id"] for p in meta["packages"] if p["name"] in ROOTS and p["source"] is None]
    seen, stack = set(), list(roots)
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    return [by_id[i] for i in seen]


def license_files(pkg):
    root = pathlib.Path(pkg["manifest_path"]).parent
    found = []
    if pkg.get("license_file"):
        found.append(root / pkg["license_file"])
    found += sorted(p for p in root.iterdir() if p.is_file() and FILES.match(p.name))
    unique = []
    for p in found:
        if p.resolve() not in [u.resolve() for u in unique]:
            unique.append(p)
    return unique


def normal(text):
    return re.sub(r"\s+", " ", text).strip()


def main():
    meta = metadata()
    pkgs = sorted(
        (p for p in shipped(meta) if not p["name"].startswith("fx-")),
        key=lambda p: (p["name"], p["version"]),
    )
    texts = {}  # normalized text -> label
    out = [
        "Pathdash — avisos de terceiros / third-party notices",
        "",
        "O Pathdash (MIT OR Apache-2.0) inclui o código dos crates abaixo, cada um com a",
        "sua licença. Pathdash (MIT OR Apache-2.0) includes the code of the crates below,",
        "each under its own license. Generated by tools/third-party-notices.py.",
        "",
        f"{len(pkgs)} crates.",
        "",
    ]
    missing = []
    for p in pkgs:
        head = f"{p['name']} {p['version']} — {p.get('license') or 'see files'}"
        out += ["=" * 78, head]
        if p.get("authors"):
            out.append("Authors: " + ", ".join(p["authors"]))
        if p.get("repository"):
            out.append(p["repository"])
        files = license_files(p)
        if not files:
            missing.append(p["name"])
            out.append(
                "(the published crate has no license file: the standard texts of its"
                " licenses are at the end of this file; copyright by the authors above)"
            )
        for f in files:
            try:
                body = f.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            key = normal(body)
            if key in texts:
                out.append(f"[{f.name}: same text as {texts[key]}]")
                continue
            texts[key] = f"{p['name']} {p['version']} / {f.name}"
            out += ["", f"--- {f.name} ---", body.rstrip(), ""]
        out.append("")
    # Standard texts, for the crates that publish none of their own.
    apache = pathlib.Path("LICENSE-APACHE").read_text(encoding="utf-8")
    mit = re.sub(
        r"^Copyright.*$",
        "Copyright (c) the authors of the crate",
        pathlib.Path("LICENSE-MIT").read_text(encoding="utf-8"),
        count=1,
        flags=re.M,
    )
    out += [
        "=" * 78,
        "Standard license texts (for the crates above without license files)",
        "",
        "--- MIT ---",
        mit.rstrip(),
        "",
        "--- Apache-2.0 ---",
        apache.rstrip(),
        "",
    ]
    pathlib.Path("THIRD-PARTY-NOTICES.txt").write_text(
        "\n".join(out) + "\n", encoding="utf-8", newline="\n"
    )
    size = pathlib.Path("THIRD-PARTY-NOTICES.txt").stat().st_size
    print(f"{len(pkgs)} crates, {len(texts)} distinct texts, {size / 1024:.0f} KB")
    if missing:
        print("without license files:", ", ".join(missing), file=sys.stderr)


if __name__ == "__main__":
    main()
